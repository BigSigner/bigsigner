def animal_name(fingerprint: bytes) -> str:
    """Adjective, color, animal, and the last two fingerprint hex characters."""
    value = int.from_bytes(fingerprint[:3], "big")
    adjective = ADJECTIVES[value % len(ADJECTIVES)]
    value //= len(ADJECTIVES)
    color = COLORS[value % len(COLORS)]
    value //= len(COLORS)
    animal = ANIMALS[value % len(ANIMALS)]
    return f"{adjective} {color} {animal} {fingerprint.hex()[-2:].upper()}"
